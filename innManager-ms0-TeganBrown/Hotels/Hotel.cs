using InnManager.Billing;
using InnManager.Employees;
using InnManager.Enums;
using InnManager.Guests;
using InnManager.Housekeeping;
using InnManager.Reservations;
using InnManager.Rooms;
using InnManager.Services;
using System;
using System.Collections.Generic;
using System.Text;

namespace InnManager.Hotels
{
    /// <summary>
    /// Represents a hotel in the inn management system.
    /// </summary>
    public class Hotel
    {
        #region Properties
        /// <summary>
        /// Gets or sets the name of the hotel.
        /// </summary>
        public string Name { get; init; }
        /// <summary>
        /// Gets or sets the type of the hotel, represented by the HotelType enum. This property allows for categorization of hotels into predefined types such as Boutique, Resort, Business, etc.
        /// </summary>
        public HotelType Type { get; init; }
        /// <summary>
        /// Gets the list of rooms in the hotel.
        /// </summary>
        public ObservableCollection<Room> Rooms { get; } = new ObservableCollection<Room>();
        /// <summary>
        /// Gets the list of guests in the hotel.
        /// </summary>
        public ObservableCollection<Guest> Guests { get; } = new ObservableCollection<Guest>();
        /// <summary>
        /// Gets the list of reservations in the hotel. 
        /// </summary>
        public ObservableCollection<Reservation> Reservations { get; } = new ObservableCollection<Reservation>();
        /// <summary>
        /// Gets the list of services offered by the hotel.
        /// </summary>
        public ObservableCollection<Service> Services { get; } = new ObservableCollection<Service>();
        /// <summary>
        /// Gets the list of invoices generated by the hotel.
        /// </summary>
        public ObservableCollection<Invoice> Invoices { get; } = new ObservableCollection<Invoice>();
        /// <summary>
        /// Gets the list of payments made by guests in the hotel.
        /// </summary>
        public ObservableCollection<Payment> Payments { get; } = new ObservableCollection<Payment>();
        /// <summary>
        /// Gets the list of employees working in the hotel.
        /// </summary>
        public ObservableCollection<Employee> Employees { get; } = new ObservableCollection<Employee>();
        /// <summary>
        /// Gets the list of housekeeping tasks assigned to the hotel.
        /// </summary>
        public ObservableCollection<HousekeepingTask> HousekeepingTasks { get; } = new ObservableCollection<HousekeepingTask>();
        /// <summary>
        /// Gets the count of available rooms in the hotel.
        /// </summary>
        public int AvailableRoomCount 
        {
            get
            {
                int count = 0;
                foreach (Room r in Rooms)
                {
                    if (r.Status == RoomStatus.Available)
                    {
                        count++;
                    }
                }
                return count;
            }
        }
        /// <summary>
        /// Gets the count of occupied rooms in the hotel.
        /// </summary>
        public int OccupiedRoomCount
        {
            get
            {
                int count = 0;
                foreach (Room r in Rooms)
                {
                    if (r.Status == RoomStatus.Occupied)
                    {
                        count++;
                    }
                }
                return count;
            }
        }
        #endregion
        /// <summary>
        /// Initializes a new instance of the Hotel class with the specified name and type.
        /// </summary>
        /// <param name="name">The name of the hotel</param>
        /// <param name="type">the type of the hotel</param>
        public Hotel(string name, HotelType type)
        {
            Name = name;
            Type = type;
        }
    }
}
